'use strict';

// Source preparation only. This script never opens a database connection or
// executes PHP/migrations. Original SQL and schema managers are read-only inputs.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = relative => fs.readFileSync(path.join(root, relative), 'utf8').replace(/\r\n/g, '\n');
const engine = ' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;';
const original = read('database/schema.sql');
const tables = new Map();
for (const match of original.matchAll(/CREATE TABLE IF NOT EXISTS (\w+) \([\s\S]*?^\) ENGINE=[^;]+;/gm)) {
  tables.set(match[1], match[0]);
}
if (tables.size === 0) throw new Error('No source schema found.');

// Include tables absent from the legacy SQL, including operational criteria,
// broker mail, V2 assessments, and CLUP governance. Extract DDL strings only.
for (const file of ['SchemaManager', 'BrokerSchemaManager', 'V2SchemaManager', 'ClupSchemaManager']) {
  for (const match of read(`app/Core/${file}.php`).matchAll(/<<<'SQL'\n([\s\S]*?)\nSQL/g)) {
    const ddl = match[1].trim();
    const name = /^CREATE TABLE IF NOT EXISTS (\w+) \(/.exec(ddl)?.[1];
    if (!name || tables.has(name)) continue;
    tables.set(name, ddl.replace(/\)(?: ENGINE=[^;]+;?)?$/, ')' + engine));
  }
}

// Fields added by the current managers but absent from database/schema.sql.
const missingProperties = {
  subname: 'VARCHAR(180) NULL',
  proposed_activity: 'VARCHAR(180) NULL',
  structured_facts_json: 'LONGTEXT NULL',
  v2_assessment_json: 'LONGTEXT NULL',
  v2_eligibility_status: 'VARCHAR(50) NULL DEFAULT NULL',
  v2_iai_score: 'DECIMAL(5,2) NULL DEFAULT NULL',
};
let properties = tables.get('properties');
for (const [column, definition] of Object.entries(missingProperties)) {
  if (!new RegExp(`^  ${column} `, 'm').test(properties)) {
    properties = properties.replace(/\n  created_at /, `\n  ${column} ${definition},\n  created_at `);
  }
}
tables.set('properties', properties);

// Fail if foreign-key creation order is broken or a required table is missing.
const seen = new Set();
for (const [name, ddl] of tables) {
  for (const reference of ddl.matchAll(/REFERENCES (\w+)\(/g)) {
    if (reference[1] !== name && !seen.has(reference[1])) throw new Error(`Invalid table order: ${name} -> ${reference[1]}`);
  }
  seen.add(name);
}
for (const required of ['criteria_config', 'investor_project_profiles', 'v2_scoring_configurations', 'property_assessment_versions', 'clup_reports']) {
  if (!tables.has(required)) throw new Error(`Missing ${required}`);
}
const header = '-- WELL-YU only. Prepared for review; execute only after explicit approval.\n'
  + '-- Existing compatible tables are preserved by CREATE TABLE IF NOT EXISTS.\n'
  + '-- Before a partial-setup retry: php scripts/inspect-well-yu-database.php --plan\n'
  + '-- Existing columns/constraints are not upgraded. Review any mismatch first.\n'
  + '-- DDL is not transactionally reversible; approval is required before import.\n'
  + '-- Schema only: no accounts, demo rows, scoring defaults, or CLUP rules are inserted.\n'
  + '-- Generated by node scripts/prepare-well-yu-sql.cjs; original scripts are unchanged.\n'
  + 'USE `well_yu_db`;\n\n';
const schema = header + [...tables.values()].join('\n\n') + '\n';
const seed = '-- OPTIONAL DEMO DATA. Requires separate explicit seed approval.\n'
  + '-- NOT IDEMPOTENT: fixed IDs conflict with existing records. Do not retry on a populated database.\n'
  + '-- Keep existing users and passwords. Use the read-only inspector before any seed decision.\n'
  + '-- Use only after the WELL-YU schema, while all application tables are empty.\n'
  + '-- Includes public development passwords and legacy sample identities; never use in production.\n'
  + read('database/seed.sql').replace(/USE sfcelerate_bizstart;/g, 'USE `well_yu_db`;');
if (/sfcelerate_bizstart/i.test(schema + seed)) throw new Error('Unsafe database reference in prepared output.');
if (/^(?:INSERT|UPDATE|DELETE|DROP|TRUNCATE|ALTER|CREATE DATABASE)\b/im.test(schema)) throw new Error('Unexpected non-schema statement.');
const out = path.join(root, 'database', 'well-yu');
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'schema.sql'), schema);
fs.writeFileSync(path.join(out, 'setup.sql'), '-- Entry point: schema only; does NOT include seed.sql.\n' + schema);
fs.writeFileSync(path.join(out, 'seed.sql'), seed);
console.log(`Prepared ${tables.size} tables for well_yu_db. No SQL executed.`);
