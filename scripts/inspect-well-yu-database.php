<?php
declare(strict_types=1);

// Read-only database inspection. No bootstrap, migrations, seed execution,
// INSERT/UPDATE/DELETE/DDL, HTTP calls or login activity is invoked here.
if (PHP_SAPI !== 'cli') { http_response_code(404); exit; }
if (array_diff(array_slice($argv, 1), ['--plan']) !== []) {
    fwrite(STDERR, "Usage: php scripts/inspect-well-yu-database.php [--plan]\n");
    exit(1);
}
$root = dirname(__DIR__);

function wy_inspection_query(PDO $pdo, string $sql, array $parameters = []): array
{
    // All calls below use developer-owned, single SELECT statements. Never
    // accept SQL text, schema names or identifiers from command-line input.
    if (!preg_match('/^SELECT\b/i', $sql) || str_contains($sql, ';')) {
        throw new RuntimeException('Only single SELECT statements are allowed.');
    }
    $statement = $pdo->prepare($sql);
    $statement->execute($parameters);
    return $statement->fetchAll(PDO::FETCH_ASSOC);
}

function wy_inspection_ident(string $name): string
{
    if (!preg_match('/^[a-z][a-z0-9_]*$/D', $name)) {
        throw new RuntimeException('Unexpected schema identifier.');
    }
    return '`' . $name . '`';
}

function wy_inspection_type(string $type): string
{
    $type = strtolower(preg_replace('/\s+/', ' ', trim($type)) ?? '');
    $type = preg_replace('/\b(tinyint|smallint|mediumint|int|bigint)\s*\(\s*\d+\s*\)/', '$1', $type) ?? $type;
    return preg_replace('/\s*([(),])\s*/', '$1', $type) ?? $type;
}

function wy_inspection_plan(array $expected, array $actualTableNames, array $issues): string
{
    $plan = "-- WELL-YU only. Generated by read-only inspection; NOT executed.\n-- Approval required before importing any CREATE statements.\n-- Creates missing tables only; existing tables and records are unchanged.\n-- Rerun inspection immediately before use; existing schema must be compatible.\nUSE `well_yu_db`;\n\n";
    if ($issues !== []) {
        return $plan . "-- BLOCKED: existing schema differs; review inspection output first.\n-- No CREATE/ALTER or data statements were generated.\n";
    }
    $missing = array_diff(array_keys($expected), $actualTableNames);
    if ($missing === []) {
        return $plan . "-- All 35 application tables already exist. No schema commands needed.\n";
    }
    $seen = array_fill_keys($actualTableNames, true);
    foreach ($expected as $name => $definition) {
        if (isset($seen[$name])) { continue; }
        preg_match_all('/REFERENCES (\w+)\(/', $definition['ddl'], $parents);
        foreach ($parents[1] as $parent) {
            if ($parent !== $name && !isset($seen[$parent])) {
                throw new RuntimeException('Unsafe parent table order in prepared schema.');
            }
        }
        // ON UPDATE CURRENT_TIMESTAMP is column behavior, not a write query.
        $withoutTimestamp = str_replace('ON UPDATE CURRENT_TIMESTAMP', '', $definition['ddl']);
        if (!preg_match('/^CREATE TABLE IF NOT EXISTS [a-z][a-z0-9_]* \(/', $withoutTimestamp)
            || preg_match('/\b(?:INSERT INTO|UPDATE|DELETE FROM|REPLACE INTO|DROP|TRUNCATE|ALTER TABLE|USE)\b/', $withoutTimestamp)) {
            throw new RuntimeException('Unexpected SQL in missing-table plan.');
        }
        $plan .= $definition['ddl'] . "\n\n";
        $seen[$name] = true;
    }
    return $plan;
}

// Offline safety tests load only the pure helpers; no connection is opened.
if (defined('WELL_YU_INSPECTION_FUNCTIONS_ONLY')) { return; }

try {
    $config = require $root . '/app/config.php';
    if ($config['db']['name'] !== 'well_yu_db' || $config['app']['auto_migrate'] || $config['app']['auto_seed'] || $config['db']['auto_create']) {
        throw new RuntimeException('WELL-YU target or disabled-automation check failed.');
    }
    foreach (['host', 'charset'] as $part) {
        if (preg_match('/[;\x00-\x20]/', (string) $config['db'][$part])) { throw new RuntimeException('Unsafe DSN component.'); }
    }
    // A direct, explicitly named connection avoids Database::pdo() session SET
    // commands as well as every path capable of automatic schema/data writes.
    $pdo = new PDO(sprintf('mysql:host=%s;port=%d;dbname=well_yu_db;charset=utf8mb4', $config['db']['host'], $config['db']['port']), $config['db']['user'], $config['db']['pass'], [
        PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
        PDO::ATTR_EMULATE_PREPARES => false,
        PDO::MYSQL_ATTR_MULTI_STATEMENTS => false,
    ]);
    $server = wy_inspection_query($pdo, 'SELECT DATABASE() AS active_database, VERSION() AS server_version, @@port AS server_port, @@hostname AS server_hostname, @@server_id AS server_id, CURRENT_TIMESTAMP AS inspected_at')[0];
    if ($server['active_database'] !== 'well_yu_db') { throw new RuntimeException('Unexpected active database.'); }
    $schema = str_replace("\r\n", "\n", (string) file_get_contents($root . '/database/well-yu/schema.sql'));
    $setup = str_replace("\r\n", "\n", (string) file_get_contents($root . '/database/well-yu/setup.sql'));
    if ($setup !== "-- Entry point: schema only; does NOT include seed.sql.\n" . $schema
        || str_contains($schema, 'sfcelerate_bizstart')
        || preg_match('/^(INSERT|UPDATE|DELETE|REPLACE|DROP|TRUNCATE|ALTER|CREATE DATABASE)\b/mi', $schema)) {
        throw new RuntimeException('Prepared setup/schema safety check failed.');
    }
    preg_match_all('/CREATE TABLE IF NOT EXISTS (\w+) \((.*?)^\) ENGINE=[^;]+;/ms', $schema, $definitions, PREG_SET_ORDER);
    $expected = [];
    foreach ($definitions as $definition) { $expected[$definition[1]] = ['ddl' => $definition[0], 'body' => $definition[2]]; }
    if (count($expected) !== 35) { throw new RuntimeException('Expected 35 application tables.'); }

    $actualTables = [];
    foreach (wy_inspection_query($pdo, "SELECT TABLE_NAME, TABLE_TYPE, ENGINE, CREATE_TIME FROM information_schema.tables WHERE table_schema = 'well_yu_db' ORDER BY TABLE_NAME") as $table) {
        $actualTables[$table['TABLE_NAME']] = $table;
    }
    $actualColumns = [];
    foreach (wy_inspection_query($pdo, "SELECT TABLE_NAME, COLUMN_NAME, COLUMN_TYPE, IS_NULLABLE, EXTRA, COLUMN_DEFAULT FROM information_schema.columns WHERE table_schema = 'well_yu_db' ORDER BY TABLE_NAME, ORDINAL_POSITION") as $column) {
        $actualColumns[$column['TABLE_NAME']][$column['COLUMN_NAME']] = $column;
    }
    $indexes = [];
    foreach (wy_inspection_query($pdo, "SELECT TABLE_NAME, INDEX_NAME, NON_UNIQUE, COLUMN_NAME FROM information_schema.statistics WHERE table_schema = 'well_yu_db' ORDER BY TABLE_NAME, INDEX_NAME, SEQ_IN_INDEX") as $index) {
        $indexes[$index['TABLE_NAME']][$index['INDEX_NAME']]['columns'][] = $index['COLUMN_NAME'];
        $indexes[$index['TABLE_NAME']][$index['INDEX_NAME']]['unique'] = (int) $index['NON_UNIQUE'] === 0;
    }
    $foreignKeys = wy_inspection_query($pdo, "SELECT k.TABLE_NAME, k.CONSTRAINT_NAME, k.COLUMN_NAME, k.REFERENCED_TABLE_SCHEMA, k.REFERENCED_TABLE_NAME, k.REFERENCED_COLUMN_NAME, r.DELETE_RULE, r.UPDATE_RULE FROM information_schema.key_column_usage k JOIN information_schema.referential_constraints r ON r.CONSTRAINT_SCHEMA = k.CONSTRAINT_SCHEMA AND r.TABLE_NAME = k.TABLE_NAME AND r.CONSTRAINT_NAME = k.CONSTRAINT_NAME WHERE k.TABLE_SCHEMA = 'well_yu_db' AND k.REFERENCED_TABLE_NAME IS NOT NULL ORDER BY k.TABLE_NAME, k.CONSTRAINT_NAME, k.ORDINAL_POSITION");
    $issues = [];
    foreach ($foreignKeys as $fk) {
        if ($fk['REFERENCED_TABLE_SCHEMA'] !== 'well_yu_db') { $issues[] = 'External foreign-key target: ' . $fk['TABLE_NAME'] . '.' . $fk['CONSTRAINT_NAME']; }
    }
    $expectedFkCount = 0;
    $expectedColumnCount = 0;
    $rows = [];
    foreach ($expected as $name => $definition) {
        preg_match_all('/^  ([a-z][a-z0-9_]*)\s+([A-Z]+(?:\([^)]*\))?(?: UNSIGNED)?)([^\n]*)/m', $definition['body'], $columnDefinitions, PREG_SET_ORDER);
        $expectedColumnCount += count($columnDefinitions);
        preg_match_all('/CONSTRAINT (\w+)\s+FOREIGN KEY\s*\((\w+)\)\s+REFERENCES (\w+)\((\w+)\)(?: ON DELETE (CASCADE|SET NULL|RESTRICT))?/', $definition['body'], $expectedFks, PREG_SET_ORDER);
        $expectedFkCount += count($expectedFks);
        if (!isset($actualTables[$name])) { continue; }
        if ($actualTables[$name]['TABLE_TYPE'] !== 'BASE TABLE' || $actualTables[$name]['ENGINE'] !== 'InnoDB') { $issues[] = 'Unexpected table type/engine: ' . $name; continue; }
        $rows[$name] = (int) wy_inspection_query($pdo, 'SELECT COUNT(*) AS total FROM `well_yu_db`.' . wy_inspection_ident($name))[0]['total'];
        foreach ($columnDefinitions as $column) {
            $actual = $actualColumns[$name][$column[1]] ?? null;
            if ($actual === null) { $issues[] = 'Missing column: ' . $name . '.' . $column[1]; continue; }
            $desiredType = wy_inspection_type($column[2]);
            $actualType = wy_inspection_type($actual['COLUMN_TYPE']);
            if (!($desiredType === 'json' && $actualType === 'longtext') && $desiredType !== $actualType) { $issues[] = 'Column type differs: ' . $name . '.' . $column[1] . ' (' . $actualType . ' versus ' . $desiredType . ')'; }
            $nullable = !preg_match('/\bNOT NULL\b|\bPRIMARY KEY\b/', $column[3]);
            if ($nullable !== ($actual['IS_NULLABLE'] === 'YES')) { $issues[] = 'Column nullability differs: ' . $name . '.' . $column[1]; }
            if (str_contains($column[3], 'AUTO_INCREMENT') && !str_contains($actual['EXTRA'], 'auto_increment')) { $issues[] = 'Missing AUTO_INCREMENT: ' . $name . '.' . $column[1]; }
            if (str_contains($column[3], 'GENERATED ALWAYS') && !str_contains($actual['EXTRA'], 'GENERATED')) { $issues[] = 'Missing generated expression: ' . $name . '.' . $column[1]; }
            if (str_contains($column[3], 'PRIMARY KEY') && ($indexes[$name]['PRIMARY']['columns'] ?? []) !== [$column[1]]) { $issues[] = 'Missing/different primary key: ' . $name . '.' . $column[1]; }
            if (str_contains($column[3], 'UNIQUE')) {
                $unique = array_filter($indexes[$name] ?? [], static fn (array $index): bool => $index['unique'] && $index['columns'] === [$column[1]]);
                if ($unique === []) { $issues[] = 'Missing inline uniqueness: ' . $name . '.' . $column[1]; }
            }
        }
        preg_match_all('/^  (?:(UNIQUE) )?KEY (\w+) \(([^)]+)\)/m', $definition['body'], $expectedIndexes, PREG_SET_ORDER);
        foreach ($expectedIndexes as $index) {
            $actual = $indexes[$name][$index[2]] ?? null;
            $columns = array_map('trim', explode(',', $index[3]));
            if ($actual === null || $actual['columns'] !== $columns || $actual['unique'] !== ($index[1] === 'UNIQUE')) { $issues[] = 'Missing/different index: ' . $name . '.' . $index[2]; }
        }
        foreach ($expectedFks as $fk) {
            $match = array_values(array_filter($foreignKeys, static fn (array $actual): bool => $actual['TABLE_NAME'] === $name && $actual['CONSTRAINT_NAME'] === $fk[1]));
            $actual = $match[0] ?? null;
            if ($actual === null || $actual['COLUMN_NAME'] !== $fk[2] || $actual['REFERENCED_TABLE_NAME'] !== $fk[3] || $actual['REFERENCED_COLUMN_NAME'] !== $fk[4] || $actual['DELETE_RULE'] !== ($fk[5] ?? 'RESTRICT')) { $issues[] = 'Missing/different foreign key: ' . $name . '.' . $fk[1]; }
        }
    }

    // Match only public seed identities; never print real emails or password hashes.
    $seed = (string) file_get_contents($root . '/database/well-yu/seed.sql');
    preg_match_all("/\((\d+), '(admin|seller|investor)', '([^']+)', (?:'[^']*'|NULL), '([^']+)', '([^']+)'/", $seed, $seedUsers, PREG_SET_ORDER);
    $demo = [];
    if (isset($actualColumns['users']['id'], $actualColumns['users']['email'], $actualColumns['users']['password_hash'], $actualColumns['users']['role'])) {
        $users = wy_inspection_query($pdo, 'SELECT id, role, email, password_hash FROM `well_yu_db`.`users` ORDER BY id');
        foreach ($seedUsers as $expectedUser) {
            $matches = array_values(array_filter($users, static fn (array $user): bool => (int) $user['id'] === (int) $expectedUser[1] || strtolower($user['email']) === strtolower($expectedUser[4])));
            $demo[] = [
                'expected_id' => (int) $expectedUser[1], 'demo_email' => $expectedUser[4], 'expected_role' => $expectedUser[2],
                'matches' => array_map(static fn (array $user): array => ['id' => (int) $user['id'], 'role' => $user['role'], 'same_demo_email' => strtolower($user['email']) === strtolower($expectedUser[4]), 'same_seed_password_hash' => hash_equals($expectedUser[5], (string) $user['password_hash'])], $matches),
            ];
        }
    }
    $missing = array_values(array_diff(array_keys($expected), array_keys($actualTables)));
    $extra = array_values(array_diff(array_keys($actualTables), array_keys($expected)));
    $planPath = $root . '/database/well-yu/complete-missing-tables.sql';
    $plan = null;
    if (in_array('--plan', $argv, true)) {
        // Replacing any older plan with comments on a conflict prevents stale
        // DDL from appearing usable after a new incompatibility is found.
        $plan = wy_inspection_plan($expected, array_keys($actualTables), $issues);
        file_put_contents($planPath, $plan);
    }
    echo json_encode([
        'server' => $server,
        'automatic_writes' => ['auto_migrate' => false, 'auto_seed' => false, 'auto_create' => false, 'private_admin_setup_present' => is_file($root . '/app/admin-access.local.php')],
        'expected_application_tables' => count($expected), 'present_application_tables' => count($expected) - count($missing),
        'schema_complete' => $missing === [] && $issues === [],
        'expected_columns' => $expectedColumnCount, 'expected_foreign_keys' => $expectedFkCount, 'actual_foreign_keys' => count($foreignKeys),
        'missing_tables' => $missing, 'extra_tables' => $extra, 'schema_issues' => $issues,
        'table_row_counts' => $rows, 'demo_accounts' => $demo,
        'optional_seed_user_count' => count($seedUsers),
        'schema_plan_file' => $plan === null ? null : 'database/well-yu/complete-missing-tables.sql',
        'schema_plan_has_ddl' => $plan !== null && str_contains($plan, 'CREATE TABLE'),
        'setup_sha256' => hash_file('sha256', $root . '/database/well-yu/setup.sql'),
        'database_write_statements_executed' => 0,
    ], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR) . "\n";
    exit($issues === [] && $missing === [] ? 0 : 2);
} catch (Throwable $error) {
    fwrite(STDERR, "Inspection failed; no database writes were attempted. " . ($error instanceof PDOException ? 'Check database availability and private credentials.' : $error->getMessage()) . "\n");
    exit(1);
}
